import { test, expect } from "@playwright/test";

test("POS terpisah: produk, stok, penjualan, invoice mini, dan cetak stok", async ({ page }, testInfo) => {
  const suffix = testInfo.project.name;
  const name = `Sepatu uji ${suffix}`;
  const sku = `POS-${suffix.toUpperCase()}`;
  await page.goto("/admin/pos");
  await expect(page).toHaveURL(/\/admin\/login/);
  await page.getByLabel("Email", { exact: true }).fill("second-admin@example.test");
  await page.getByLabel("Password").fill("second-e2e-password");
  await page.getByRole("button", { name: "Masuk", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Kasir POS", exact: true })).toBeVisible();
  const ticketCounts = await (await page.request.get("/api/days")).json();
  await page.getByRole("link", { name: "Produk & stok", exact: true }).click();
  await page.getByRole("button", { name: "+ Tambah produk", exact: true }).click();
  await page.getByLabel("SKU / kode barang").fill(sku);
  await page.getByLabel("Nama produk", { exact: true }).fill(name);
  await page.getByLabel("Harga jual (Rp)").fill("35000");
  await page.getByLabel("Stok awal").fill("5");
  await page.getByRole("button", { name: "Simpan", exact: true }).click();
  const row = page.getByTestId(`product-${sku}`);
  await expect(row.getByTestId("product-stock")).toHaveText("5");
  await row.getByRole("button", { name: "Ubah stok", exact: true }).click();
  await page.getByLabel("Perubahan jumlah").fill("2");
  await page.getByLabel("Alasan perubahan").fill("Stok masuk pengujian");
  await page.getByRole("button", { name: "Simpan", exact: true }).click();
  await expect(row.getByTestId("product-stock")).toHaveText("7");
  await page.screenshot({ path: testInfo.outputPath("pos-products.png"), fullPage: true });
  await page.getByRole("link", { name: "Kasir", exact: true }).click();
  await page.getByLabel("Cari nama atau SKU").fill(sku);
  await page.getByRole("button", { name: `Tambah ${name}`, exact: true }).click();
  await page.getByRole("button", { name: `Tambah jumlah ${name}`, exact: true }).click();
  await page.getByLabel("Nama pelanggan").fill("Pelanggan uji");
  await page.getByLabel("Diskon (Rp)").fill("5000");
  await page.getByLabel("Uang diterima (Rp)").fill("100000");
  await expect(page.getByTestId("pos-total")).toContainText("65.000");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("pos-register.png"), fullPage: true });
  const saved = page.waitForResponse(response => response.url().endsWith("/api/admin/pos/sales") && response.status() === 201);
  await page.getByRole("button", { name: "Simpan penjualan & buat invoice", exact: true }).click();
  const invoice = await (await saved).json();
  await expect(page).toHaveURL(new RegExp(`/admin/pos/transaksi/${invoice.id}$`));
  await expect(page.getByTestId("pos-invoice")).toContainText(name);
  await expect(page.getByTestId("pos-invoice")).toContainText("second-admin@example.test");
  await expect(page.getByTestId("pos-invoice")).toContainText("35.000");
  await expect(page.getByTestId("pos-invoice-number")).toHaveText(invoice.invoiceNumber);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("pos-invoice.png"), fullPage: true });
  await page.pdf({ path: testInfo.outputPath("invoice-mini.pdf"), preferCSSPageSize: true, printBackground: true });
  await page.evaluate(() => { (window as unknown as { printCalls: number }).printCalls = 0; window.print = () => { (window as unknown as { printCalls: number }).printCalls++; }; });
  await page.getByRole("button", { name: "Cetak / simpan PDF" }).click();
  expect(await page.evaluate(() => (window as unknown as { printCalls: number }).printCalls)).toBe(1);
  await page.getByRole("link", { name: "Versi A4", exact: true }).click();
  await expect(page).toHaveURL(/paper=a4/);
  await expect(page.getByRole("link", { name: "Ukuran contoh DealPOS", exact: true })).toBeVisible();
  await page.pdf({ path: testInfo.outputPath("invoice-a4.pdf"), preferCSSPageSize: true });
  await page.getByRole("link", { name: "Produk & stok", exact: true }).click();
  await expect(row.getByTestId("product-stock")).toHaveText("5");
  await row.getByRole("link", { name: "Riwayat stok →", exact: true }).click();
  await expect(page.getByText(invoice.invoiceNumber, { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Transaksi", exact: true }).click();
  await page.getByLabel("Cari invoice atau pelanggan").fill(invoice.invoiceNumber);
  await page.getByRole("button", { name: "Cari", exact: true }).click();
  await page.getByRole("link", { name: invoice.invoiceNumber, exact: true }).click();
  await expect(page.getByTestId("pos-invoice-number")).toHaveText(invoice.invoiceNumber);
  await page.getByRole("link", { name: "Cetak stok", exact: true }).click();
  await expect(page.getByTestId("pos-stock-report")).toContainText(sku);
  await page.pdf({ path: testInfo.outputPath("stock.pdf"), preferCSSPageSize: true });
  expect(await (await page.request.get("/api/days")).json()).toEqual(ticketCounts);
});

test("transaksi yang koneksinya terputus dapat dilanjutkan tanpa mengurangi stok dua kali", async ({ page }, testInfo) => {
  await page.goto("/admin/login");
  await page.getByLabel("Email", { exact: true }).fill("admin@example.test");
  await page.getByLabel("Password").fill("e2e-password");
  await page.getByRole("button", { name: "Masuk", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Dashboard", exact: true })).toBeVisible();
  const sku = `RETRY-${testInfo.project.name.toUpperCase()}`;
  const name = `Barang retry ${testInfo.project.name}`;
  const response = await page.request.post("/api/admin/pos/products", { data: { sku, name, stock: 1, price: 35_000 } });
  expect(response.status()).toBe(201);
  const product = await response.json();
  await page.goto("/admin/pos");
  await page.getByLabel("Cari nama atau SKU").fill(sku);
  await page.getByRole("button", { name: `Tambah ${name}`, exact: true }).click();
  let savedId = "";
  await page.route("**/api/admin/pos/sales", async route => {
    if (savedId) { await route.continue(); return; }
    const saved = await route.fetch();
    expect(saved.status()).toBe(201);
    savedId = (await saved.json()).id;
    await route.abort("connectionfailed");
  });
  await page.getByRole("button", { name: "Simpan penjualan & buat invoice", exact: true }).click();
  await expect(page.getByRole("alert")).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Coba simpan kembali", exact: true }).first().click();
  await expect(page).toHaveURL(new RegExp(`/admin/pos/transaksi/${savedId}$`));
  const products = await (await page.request.get("/api/admin/pos/products")).json();
  expect(products.find((row: { id: string }) => row.id === product.id).stock).toBe(0);
  expect(await page.evaluate(() => sessionStorage.getItem("whs.pos.pending-sale.v1"))).toBeNull();
});
