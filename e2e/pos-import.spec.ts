import { test, expect } from "@playwright/test";
import ExcelJS from "exceljs";

test("impor CSV dan Excel: pratinjau, validasi, stok akhir, stok masuk, serta pemulihan koneksi", async ({ page }, testInfo) => {
  await page.goto("/admin/login");
  await page.getByLabel("Email", { exact: true }).fill("admin@example.test");
  await page.getByLabel("Password").fill("e2e-password");
  await page.getByRole("button", { name: "Masuk", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Dashboard", exact: true })).toBeVisible();
  const sku = `IMPORT-${testInfo.project.name.toUpperCase()}`, newSku = `${sku}-NEW`;
  await page.request.post("/api/admin/pos/products", { data: { sku, name: "Produk awal impor", price: 35000, stock: 10 } });
  const before = await (await page.request.get("/api/days")).json();
  await page.goto("/admin/pos/produk");
  await page.getByRole("link", { name: "Impor Excel / CSV", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Impor produk & stok" })).toBeVisible();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("link", { name: "Unduh template Excel", exact: true }).click();
  expect((await downloadPromise).suggestedFilename()).toBe("template-produk.xlsx");
  await page.getByLabel("File produk").setInputFiles({ name: "salah.csv", mimeType: "text/csv", buffer: Buffer.from(`SKU,Stok\n${sku},5\n${sku},8`) });
  await page.getByRole("button", { name: "Lihat pratinjau", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Perbaiki baris" })).toContainText("Baris 3");
  await expect(page.getByRole("button", { name: "Simpan perubahan stok", exact: true })).toHaveCount(0);
  await page.getByLabel("File produk").setInputFiles({ name: "produk.csv", mimeType: "text/csv", buffer: Buffer.from(`SKU,Nama,Harga,Stok\n${sku},,,4\n${newSku},Produk baru impor,25000,6`) });
  await page.getByRole("button", { name: "Lihat pratinjau", exact: true }).click();
  await expect(page.getByTestId(`import-${sku}`)).toContainText("Produk awal impor");
  expect((await (await page.request.get("/api/admin/pos/products")).json()).find((p: { sku: string }) => p.sku === sku).stock).toBe(10);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("import-preview.png"), fullPage: true });
  await page.getByRole("button", { name: "Simpan perubahan stok", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Impor berhasil disimpan" })).toBeVisible();
  await page.getByRole("link", { name: "Lihat produk & stok", exact: true }).click();
  await expect(page.getByTestId(`product-${sku}`).getByTestId("product-stock")).toHaveText("4");
  await expect(page.getByTestId(`product-${newSku}`).getByTestId("product-stock")).toHaveText("6");
  await page.getByRole("link", { name: "Impor Excel / CSV", exact: true }).click();
  const book = new ExcelJS.Workbook(); book.addWorksheet("Produk").addRows([["SKU", "Stok"], [sku, 3]]);
  await page.getByLabel("File produk").setInputFiles({ name: "stok-masuk.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from(await book.xlsx.writeBuffer()) });
  await page.getByLabel("Cara memperbarui stok").selectOption("ADD");
  await page.getByRole("button", { name: "Lihat pratinjau", exact: true }).click();
  await expect(page.getByTestId(`import-${sku}`)).toBeVisible();
  let saved = false;
  await page.route(/\/api\/admin\/pos\/imports\/[^/]+$/, async route => {
    if (route.request().method() !== "POST" || saved) return route.continue();
    const response = await route.fetch(); expect(response.status()).toBe(200); saved = true;
    await route.abort("connectionfailed");
  });
  await page.getByRole("button", { name: "Simpan perubahan stok", exact: true }).click();
  await expect(page.getByRole("button", { name: "Coba simpan kembali", exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Periksa impor sebelumnya", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Impor berhasil disimpan" })).toBeVisible();
  await page.getByRole("link", { name: "Lihat produk & stok", exact: true }).click();
  await expect(page.getByTestId(`product-${sku}`).getByTestId("product-stock")).toHaveText("7");
  await page.getByTestId(`product-${sku}`).getByRole("link", { name: "Riwayat stok →" }).click();
  await expect(page.getByText(/Impor stok masuk: stok-masuk.xlsx/)).toBeVisible();
  expect(await (await page.request.get("/api/days")).json()).toEqual(before);
});
